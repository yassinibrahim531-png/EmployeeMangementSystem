    private void deleteEmployeeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteEmployeeButtonActionPerformed
        String id = employeeIdField.getText().trim();

        if (!validator.isNotEmpty(id)) {
            JOptionPane.showMessageDialog(this, "Please enter an employee ID.");
            return;
        }

        if (!validator.isValidInteger(id)) {
            JOptionPane.showMessageDialog(this, "Please enter a valid employee ID.");
            return;
        }

        int employeeId = Integer.parseInt(id);

        if (employeeManager.searchEmployeeById(employeeId) == null) {
            JOptionPane.showMessageDialog(this, "Employee not found.");
            return;
        }

        int choice = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete this employee?",
                "Confirm Deletion",
                JOptionPane.YES_NO_OPTION
        );

        if (choice != JOptionPane.YES_OPTION) {
            return;
        }

        boolean deleted = employeeManager.deleteEmployee(employeeId);

        if (deleted) {
            JOptionPane.showMessageDialog(this, "Employee deleted successfully.");
            employeeIdField.setText("");

            try {
                FileHandler fileHandler = new FileHandler();
                fileHandler.saveEmployees(employeeManager.getAllEmployees());
            } catch (java.io.FileNotFoundException e) {
                JOptionPane.showMessageDialog(this, "Error saving employee data.");
            }

        } else {
            JOptionPane.showMessageDialog(this, "Failed to delete employee.");
        }
    }//GEN-LAST:event_deleteEmployeeButtonActionPerformed

