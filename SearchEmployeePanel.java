    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
        String value = searchField.getText().trim();

        if (!validator.isNotEmpty(value)) {
            JOptionPane.showMessageDialog(this, "Please enter a value to search.");
            return;
        }

        String searchType = searchTypeComboBox.getSelectedItem().toString();
        DefaultTableModel model = (DefaultTableModel) employeeTable.getModel();
        model.setRowCount(0);

        if (searchType.equals("ID")) {

            if (!validator.isValidInteger(value)) {
                JOptionPane.showMessageDialog(this, "Please enter a valid employee ID.");
                return;
            }

            int employeeId = Integer.parseInt(value);

            Employee employee = employeeManager.searchEmployeeById(employeeId);

            if (employee == null) {
                JOptionPane.showMessageDialog(this, "Employee not found.");
                return;
            }

            String departmentName = "";

            if (employee.getDepartment() != null) {
                departmentName = employee.getDepartment().getDepartmentName();
            }

            model.addRow(new Object[]{
                employee.getEmployeeId(),
                employee.getFullName(),
                departmentName,
                employee.getAge(),
                employee.getPosition(),
                employee.getEmployeeType(),
                employee.calculateMonthlySalary()
            });
        } else if (searchType.equals("Department")) {
            List<Employee> employees = employeeManager.searchEmployeesByDepartment(value);
            if (employees.isEmpty()) {
                JOptionPane.showMessageDialog(this, "No employees found in this department.");
                return;
            }

            for (Employee employee : employees) {
                String departmentName = "";

                if (employee.getDepartment() != null) {
                    departmentName = employee.getDepartment().getDepartmentName();
                }
                    model.addRow(new Object[]{
                        employee.getEmployeeId(),
                        employee.getFullName(),
                        departmentName,
                        employee.getAge(),
                        employee.getPosition(),
                        employee.getEmployeeType(),
                        employee.calculateMonthlySalary()
                    });
                

            }
        }
    }//GEN-LAST:event_searchButtonActionPerformed

