    private void findEmployeeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_findEmployeeButtonActionPerformed
        String id = employeeID.getText().trim();

        if (!validator.isNotEmpty(id)) {
            JOptionPane.showMessageDialog(this, "Please enter an employee ID.");
            return;
        }

        if (!validator.isValidInteger(id)) {
            JOptionPane.showMessageDialog(this, "Please enter a valid employee ID.");
            return;
        }

        int employeeId = Integer.parseInt(id);

        currentEmployee = employeeManager.searchEmployeeById(employeeId);

        if (currentEmployee == null) {
            JOptionPane.showMessageDialog(this, "Employee not found.");
            return;
        }

        FullNameField.setText(currentEmployee.getFullName());

        if (currentEmployee.getDepartment() != null) {
            departmentField.setText(currentEmployee.getDepartment().getDepartmentName());
        } else {
            departmentField.setText("");
        }

        ageField.setText(String.valueOf(currentEmployee.getAge()));
        positionField.setText(currentEmployee.getPosition());

        employeeTypeComboBox.setSelectedItem(currentEmployee.getEmployeeType());

        if (currentEmployee instanceof FullTimeEmployee) {
            FullTimeEmployee fullTimeEmployee = (FullTimeEmployee) currentEmployee;

            firstSalaryField.setText(String.valueOf(fullTimeEmployee.getBasicMonthlySalary()));
            secondSalaryField.setText(String.valueOf(fullTimeEmployee.getMonthlyBonus()));

        } else if (currentEmployee instanceof PartTimeEmployee) {
            PartTimeEmployee partTimeEmployee = (PartTimeEmployee) currentEmployee;

            firstSalaryField.setText(String.valueOf(partTimeEmployee.getHourlyPaymentRate()));
            secondSalaryField.setText(String.valueOf(partTimeEmployee.getHoursWorkedPerMonth()));
        }
    }//GEN-LAST:event_findEmployeeButtonActionPerformed

