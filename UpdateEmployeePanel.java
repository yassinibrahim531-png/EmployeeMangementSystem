    private void updateEmployeeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateEmployeeButtonActionPerformed
        String departmentName = departmentField.getText().trim();

        if (!validator.isNotEmpty(departmentName)) {
            JOptionPane.showMessageDialog(this, "Please enter a department.");
            return;
        }

        Department department = null;

        for (Department d : departmentManager.getDepartments()) {
            if (d.getDepartmentName().equalsIgnoreCase(departmentName)) {
                department = d;
                break;
            }
        }

        if (department == null) {
            JOptionPane.showMessageDialog(this, "Department not found.");
            return;
        }

        String fullName = FullNameField.getText().trim();
        String ageText = ageField.getText().trim();
        String position = positionField.getText().trim();

        if (!validator.isNotEmpty(fullName)) {
            JOptionPane.showMessageDialog(this, "Please enter the employee name.");
            return;
        }

        if (!validator.isValidAge(ageText)) {
            JOptionPane.showMessageDialog(this, "Please enter a valid age.");
            return;
        }

        if (!validator.isNotEmpty(position)) {
            JOptionPane.showMessageDialog(this, "Please enter the employee position.");
            return;
        }

        int age = Integer.parseInt(ageText);

        String employeeType = employeeTypeComboBox.getSelectedItem().toString();

        String firstSalary = firstSalaryField.getText().trim();
        String secondSalary = secondSalaryField.getText().trim();

        if (!validator.isValidSalary(firstSalary)) {
            JOptionPane.showMessageDialog(this, "Please enter a valid salary value.");
            return;
        }

        if (!validator.isValidSalary(secondSalary)) {
            JOptionPane.showMessageDialog(this, "Please enter a valid value for the second salary field.");
            return;
        }

        double firstSalaryValue = Double.parseDouble(firstSalary);
        double secondSalaryValue = Double.parseDouble(secondSalary);

        Employee updatedEmployee;

        if (employeeType.equals("Full-Time")) {
            updatedEmployee = new FullTimeEmployee(
                    firstSalaryValue,
                    secondSalaryValue,
                    currentEmployee.getEmployeeId(),
                    fullName,
                    department,
                    age,
                    position
            );

        } else {
            updatedEmployee = new PartTimeEmployee(
                    firstSalaryValue,
                    secondSalaryValue,
                    currentEmployee.getEmployeeId(),
                    fullName,
                    department,
                    age,
                    position
            );
        }

        boolean updated = employeeManager.updateEmployee(
                currentEmployee.getEmployeeId(),
                updatedEmployee
        );

        if (updated) {
            JOptionPane.showMessageDialog(this, "Employee updated successfully.");
            currentEmployee = updatedEmployee;

            try {
                FileHandler fileHandler = new FileHandler();
                fileHandler.saveEmployees(employeeManager.getAllEmployees());
            } catch (java.io.FileNotFoundException e) {
                JOptionPane.showMessageDialog(this, "Error saving employee data.");
            }
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update employee.");
        }


    }//GEN-LAST:event_updateEmployeeButtonActionPerformed

